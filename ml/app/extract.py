import json

from app.llm import chat_json
from app.schemas import ExtractionResult

SYSTEM_PROMPT = """Ты — ассистент для структурирования медицинских документов на русском языке.
Извлеки из текста истории болезни факты строго по JSON-схеме ниже.

Правила:
- Извлекай только то, что явно написано в тексте. Ничего не додумывай и не ставь диагнозов сам.
- Для каждого факта в поле evidence приводи точную дословную короткую цитату из текста.
- Отрицания не являются фактами: «суицидальные мысли отрицает» → не добавлять suicidal_ideation.
- Код МКБ-10 указывай, только если он есть в тексте или однозначно соответствует названию диагноза.
- Если рядом с диагнозом явно указан код МКБ-10, обязательно перенеси его в icd10. В text укажи название диагноза без кода. Если код не указан — icd10 = null.
- Все психиатрические и неврологические диагнозы, включая заболевания центральной, периферической и вегетативной нервной системы, помещай в diagnoses. Остальные заболевания — в comorbidities. Это правило действует независимо от заголовка раздела исходного документа.
- Например: «G90.8 Другие расстройства вегетативной (автономной) нервной системы. Подтверждённый.» → элемент diagnoses с icd10="G90.8" и status="confirmed".
- Если после формулировки диагноза стоит один или несколько знаков вопроса, укажи status="suspected". В evidence сохрани исходную цитату, включая знаки вопроса.
- Болезни связанные с ЦНС - центральной нервной системой (психиатрический/неврологический повод обращения) — СТРОГО в diagnoses; ОСТАЛЬНЫЕ НЕ связанные с нервной системой (соматические) — СТРОГО в comorbidities (в том числе и беренность).
- Если данных нет — пустой список или null.
- Ответ — только JSON, без пояснений.


JSON-схема:
{schema}
"""


def extract(text: str) -> ExtractionResult:
    schema = json.dumps(ExtractionResult.model_json_schema(), ensure_ascii=False)
    return chat_json(SYSTEM_PROMPT.format(schema=schema), text, ExtractionResult)
